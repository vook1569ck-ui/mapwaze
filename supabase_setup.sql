create table if not exists public.road_reports (
 id bigint generated by default as identity primary key,
 kind text not null check (kind in ('حادث مروري','ازدحام','طريق مغلق','خطر بالطريق','نقطة تفتيش')),
 lat double precision not null check (lat between -90 and 90),
 lng double precision not null check (lng between -180 and 180),
 created_at timestamptz not null default now()
);
alter table public.road_reports enable row level security;
grant select, insert on public.road_reports to anon, authenticated;
grant usage, select on sequence public.road_reports_id_seq to anon, authenticated;
drop policy if exists "Read recent road reports" on public.road_reports;
create policy "Read recent road reports" on public.road_reports for select to anon, authenticated using (created_at > now() - interval '7 days');
drop policy if exists "Add road reports" on public.road_reports;
create policy "Add road reports" on public.road_reports for insert to anon, authenticated with check (created_at > now() - interval '10 minutes' and kind in ('حادث مروري','ازدحام','طريق مغلق','خطر بالطريق','نقطة تفتيش') and lat between -90 and 90 and lng between -180 and 180);

create table if not exists public.road_report_confirmations (
 id bigint generated by default as identity primary key,
 report_id bigint not null references public.road_reports(id) on delete cascade,
 device_id text not null check (length(device_id) between 8 and 100),
 created_at timestamptz not null default now(),
 unique (report_id, device_id)
);
alter table public.road_report_confirmations enable row level security;
grant select, insert on public.road_report_confirmations to anon, authenticated;
drop policy if exists "Read report confirmations" on public.road_report_confirmations;
create policy "Read report confirmations" on public.road_report_confirmations for select to anon, authenticated using (created_at > now() - interval '7 days');
drop policy if exists "Add one confirmation per device" on public.road_report_confirmations;
create policy "Add one confirmation per device" on public.road_report_confirmations for insert to anon, authenticated with check (created_at > now() - interval '10 minutes' and length(device_id) between 8 and 100);
