-- MapWaze Iraq shared reports. Run in Supabase > SQL Editor > New query.
create table if not exists public.road_reports (
 id bigint generated by default as identity primary key,
 kind text not null check (kind in ('حادث مروري','ازدحام','طريق مغلق','خطر بالطريق','نقطة تفتيش')),
 lat double precision not null check (lat between -90 and 90),
 lng double precision not null check (lng between -180 and 180),
 created_at timestamptz not null default now()
);
alter table public.road_reports enable row level security;
grant select, insert on public.road_reports to anon, authenticated;
drop policy if exists "Anyone can read recent road reports" on public.road_reports;
create policy "Anyone can read recent road reports" on public.road_reports for select to anon, authenticated using (created_at > now() - interval '7 days');
drop policy if exists "Anyone can add road reports" on public.road_reports;
create policy "Anyone can add road reports" on public.road_reports for insert to anon, authenticated with check (created_at > now() - interval '10 minutes' and kind in ('حادث مروري','ازدحام','طريق مغلق','خطر بالطريق','نقطة تفتيش') and lat between -90 and 90 and lng between -180 and 180);
